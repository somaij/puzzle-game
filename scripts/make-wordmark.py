"""Traces the Jigsup wordmark from the bundled Shantell Sans ExtraBold into SVG paths.

The i (and the j used by the app icon) lose their round dot: a jigsaw piece takes its place. The
subset font has no dotless letters, so the dot contour is dropped from the glyph instead.
Writes src/ui/wordmarkPaths.ts (for the game) and scripts/icon-j.json (for make-icons.mjs). Run with `python scripts/make-wordmark.py` (needs fontTools).
"""

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
import json

FONT = 'assets/fonts/ShantellSans_800ExtraBold.ttf'
OUT = 'src/ui/wordmarkPaths.ts'
TRACKING = -20  # font units between letters, tighter like the brand mock-up

font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font['head'].unitsPerEm
ascent = font['hhea'].ascent


def contours(name):
    rec = DecomposingRecordingPen(glyphs)
    glyphs[name].draw(rec)
    out, cur = [], []
    for op, args in rec.value:
        cur.append((op, args))
        if op in ('closePath', 'endPath'):
            out.append(cur)
            cur = []
    return out


def bounds(contour):
    pen = BoundsPen(glyphs)
    for op, args in contour:
        getattr(pen, op)(*args)
    return pen.bounds


def path(contour_list, dx):
    """SVG path in a y-down space with the baseline at `ascent`."""
    pen = SVGPathPen(glyphs, lambda v: f'{round(v, 1):g}')
    for contour in contour_list:
        for op, args in contour:
            pts = [(x + dx, ascent - y) for x, y in args]
            getattr(pen, op)(*pts)
    return pen.getCommands()


def letter(ch, x, drop_dot=False):
    name = cmap[ord(ch)]
    cs = contours(name)
    dot = None
    if drop_dot:
        # The dot is the contour sitting highest in the letter.
        dot_contour = max(cs, key=lambda c: bounds(c)[1])
        cs = [c for c in cs if c is not dot_contour]
        x0, y0, x1, y1 = bounds(dot_contour)
        dot = {'cx': round(x + (x0 + x1) / 2), 'cy': round(ascent - (y0 + y1) / 2), 'size': round(max(x1 - x0, y1 - y0))}
    return path(cs, x), font['hmtx'][name][0], dot


def word(text, dotted):
    x, parts, dot = 0, [], None
    for i, ch in enumerate(text):
        d, adv, letter_dot = letter(ch, x, drop_dot=(i == dotted))
        parts.append(d)
        dot = dot or letter_dot
        x += adv + TRACKING
    return parts, x - TRACKING, dot



def without_dot_bounds(ch):
    """The letter's outline bounds without its dot, y-down like the paths."""
    cs = contours(cmap[ord(ch)])
    top = max(cs, key=lambda c: bounds(c)[1])
    bs = [bounds(c) for c in cs if c is not top]
    x0, y0 = min(b[0] for b in bs), min(b[1] for b in bs)
    x1, y1 = max(b[2] for b in bs), max(b[3] for b in bs)
    return [round(x0), round(ascent - y1), round(x1), round(ascent - y0)]


parts, width, dot = word('Jigsup', dotted=1)
descent = -font['hhea'].descent
j_path, _, j_dot = letter('j', 0, drop_dot=True)

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by scripts/make-wordmark.py from Shantell Sans ExtraBold (SIL OFL). Do not edit.\n\n')
    f.write('/** "Jigsup": "Jigs" and "up" are coloured apart; the i has no dot, a jigsaw piece goes there. */\n')
    f.write('export const WORDMARK = {\n')
    f.write(f"  width: {round(width)},\n  height: {ascent + descent},\n")
    f.write(f"  jigs: '{''.join(parts[:4])}',\n  up: '{''.join(parts[4:])}',\n")
    f.write(f"  dot: {{ cx: {dot['cx']}, cy: {dot['cy']}, size: {dot['size']} }},\n}};\n")

with open('scripts/icon-j.json', 'w', encoding='utf-8', newline='\n') as f:
    json.dump({'path': j_path, 'dot': j_dot, 'bounds': without_dot_bounds('j')}, f)
    f.write('\n')
print('wrote', OUT, 'and scripts/icon-j.json')
